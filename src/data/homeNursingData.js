export function downloadNursingRequestsExcel(requests, title = 'MediUnify_Mysore_Home_Nursing_Requests') {
  const headers = [
    'Request ID',
    'Patient Name',
    'Patient ID',
    'Age',
    'Gender',
    'Contact Phone',
    'Email',
    'Requested Nursing Service',
    'Service Category',
    'Mysore Locality',
    'Address',
    'Emergency Contact',
    'Preferred Date',
    'Preferred Time',
    'Shift / Duration',
    'Urgency',
    'Status',
    'Rejection Reason (Why Rejected)',
    'Medical Instructions / Notes',
    'Created Date'
  ];

  const escapeCSV = (val) => {
    if (val === null || val === undefined) return '""';
    const stringVal = String(val).replace(/"/g, '""');
    return `"${stringVal}"`;
  };

  const rows = requests.map((r) => [
    escapeCSV(r.id || r.requestId),
    escapeCSV(r.patientName),
    escapeCSV(r.patientId),
    escapeCSV(r.age || ''),
    escapeCSV(r.gender || ''),
    escapeCSV(r.phone || r.mobileNumber),
    escapeCSV(r.email || ''),
    escapeCSV(r.serviceName || r.requestedService),
    escapeCSV(r.serviceCategory || ''),
    escapeCSV(r.location || r.cityName),
    escapeCSV(r.address || ''),
    escapeCSV(r.emergencyContact || ''),
    escapeCSV(r.preferredDate || r.requestedDate),
    escapeCSV(r.preferredTime || ''),
    escapeCSV(r.visitDuration || r.shift || ''),
    escapeCSV(r.urgency || 'Normal'),
    escapeCSV(r.status),
    escapeCSV(r.rejectionReason || (r.status === 'Rejected' ? 'Not specified' : 'N/A')),
    escapeCSV(r.medicalInstructions || r.patientRequirement || r.notes || ''),
    escapeCSV(r.createdDate || '')
  ]);

  const csvContent = [
    headers.map((h) => `"${h}"`).join(','),
    ...rows.map((row) => row.join(','))
  ].join('\r\n');

  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');

  const todayStr = new Date().toISOString().split('T')[0];
  link.setAttribute('href', url);
  link.setAttribute('download', `${title}_${todayStr}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

